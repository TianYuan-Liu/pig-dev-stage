#!/usr/bin/env python3
"""Build Table S5 (tableS7_tissue_features.tex) from the 6-stage PLS-VIP CSV.

The original generator (pls_vip_features.py) reads deleted intermediates; this
decoupled writer reads the committed review/analyses/results/pls_vip_features.csv
(top-20 per tissue, regenerated at 6-stage) and emits the same longtable format.
Peak stage is now reported on the six stages. Real data only.
"""
from pathlib import Path
import pandas as pd

ROOT = Path("/Users/tianyuan/Desktop/github_dev/pig-dev-stage")
CSV = ROOT / "review" / "analyses" / "results" / "pls_vip_features.csv"
TEX = ROOT / "paper" / "figures" / "output" / "supplementary" / "tableS7_tissue_features.tex"
TISSUES = ["Muscle", "Brain", "Liver", "Blood", "Lung"]


def esc(s) -> str:
    if s is None or (isinstance(s, float) and pd.isna(s)):
        return ""
    s = str(s)
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
            "^": r"\textasciicircum{}"}
    return "".join(repl.get(c, c) for c in s)


def main():
    df = pd.read_csv(CSV)
    L = []
    add = L.append
    add(r"% Auto-generated by review/analyses/build_tableS5_tex.py (6-stage)")
    add(r"% Top-20 PLS-VIP developmental biomarkers per tissue")
    add(r"\begingroup")
    add(r"\scriptsize")
    add(r"\setlength{\tabcolsep}{4pt}")
    add(r"\renewcommand{\arraystretch}{1.12}")
    add(r"\begin{longtable}{@{}l r l c r p{0.46\linewidth} l@{}}")
    add(r"\caption{\textbf{Top 20 developmental-stage biomarkers per tissue (PLS-VIP).} "
        r"Genes ranked by Variable Importance in Projection (VIP) from each "
        r"tissue's final ordinal partial-least-squares model (OrdinalPLS, 6-stage); "
        r"VIP$>$1 flags above-average contribution (mean VIP$^2=1$). Biomarkers are "
        r"read directly from the model weights, not from a separate statistical "
        r"test. ``Dir.'' is the sign of the PLS regression coefficient onto the "
        r"ordinal stage index: $+$ accelerator (expression rises toward later "
        r"stage), $-$ decelerator (falls toward later stage). Symbols are from "
        r"mygene.info (pig) / UniProt; functional descriptions are online-verified "
        r"against UniProt human-reviewed Swiss-Prot and PubMed. Loci with no curated "
        r"function are labelled uncharacterised/novel. ``Peak'' is the stage with "
        r"the highest mean $\log_2$(TPM$+$1) among retained stages. \emph{Only "
        r"Muscle is leakage-robust under grouped cross-validation; for "
        r"Brain/Blood/Lung/Liver some top-VIP genes may track stage confounded with "
        r"study (see main text).} \label{tab:S5}} \\")
    add(r"\toprule")
    add(r"Tissue & Rk & Gene & Dir. & VIP & Function (online-verified) & Peak \\")
    add(r"\midrule")
    add(r"\endfirsthead")
    add(r"\multicolumn{7}{c}{\textit{Table~\ref{tab:S5} continued from previous page}} \\")
    add(r"\toprule")
    add(r"Tissue & Rk & Gene & Dir. & VIP & Function (online-verified) & Peak \\")
    add(r"\midrule")
    add(r"\endhead")
    add(r"\midrule")
    add(r"\multicolumn{7}{r}{\textit{continued on next page}} \\")
    add(r"\endfoot")
    add(r"\bottomrule")
    add(r"\endlastfoot")
    for tissue in TISSUES:
        sub = df[df.tissue == tissue].sort_values("rank")
        for i, (_, r) in enumerate(sub.iterrows()):
            tcell = esc(tissue) if i == 0 else ""
            gene_cell = r"\textit{" + esc(r["gene"]) + "}"
            dirc = "$+$" if r["sign"] == "+" else "$-$"
            add(f"{tcell} & {int(r['rank'])} & {gene_cell} & {dirc} & {float(r['vip']):.2f} & "
                f"{esc(r['function'])} & {esc(r['peak_stage'])} \\\\")
        if tissue != TISSUES[-1]:
            add(r"\midrule")
    add(r"\end{longtable}")
    add(r"\endgroup")
    TEX.write_text("\n".join(L) + "\n")
    n_blank = int((df["function"].isna() | (df["function"].astype(str).str.strip() == "")).sum())
    print(f"Saved {TEX}  ({len(df)} rows; {n_blank} genes with no curated function "
          f"-> PubMed verification pending)")


if __name__ == "__main__":
    main()
